/**
 * Validate a single record against the IntakeRequests schema "categories".
 * Returns an array of human-readable issues (empty when the record is clean).
 */
function validateRecord(record) {
  const issues = [];

  if (!PIPELINE_STAGES.includes(record.stage)) {
    issues.push(`stage "${record.stage}" is outside the schema enum`);
  }
  if (!COUNTRY_BU_VALUES.includes(record.countryBu)) {
    issues.push(`countryBu "${record.countryBu}" is outside the schema enum`);
  }
  if (record.securityMode && !SECURITY_MODE_VALUES.includes(record.securityMode)) {
    issues.push(`securityMode "${record.securityMode}" is outside the schema enum`);
  }
  if (record.timeMode && !TIME_MODE_VALUES.includes(record.timeMode)) {
    issues.push(`timeMode "${record.timeMode}" is outside the schema enum`);
  }
  if (record.revenueMode && !REVENUE_MODE_VALUES.includes(record.revenueMode)) {
    issues.push(`revenueMode "${record.revenueMode}" is outside the schema enum`);
  }
  if (record.dtFeasibility !== undefined && typeof record.dtFeasibility !== 'number') {
    issues.push(`dtFeasibility "${record.dtFeasibility}" is a ${typeof record.dtFeasibility}, schema expects Number`);
  }

  return issues;
}

function reportValidation(records) {
  console.log('🔎 Validating payload against IntakeRequests schema categories...');
  let flagged = 0;

  records.forEach((record) => {
    const issues = validateRecord(record);
    if (issues.length) {
      flagged += 1;
      console.warn(`  • ${record.oppId} (${record.requestTitle}):`);
      issues.forEach((issue) => console.warn(`      - ${issue}`));
    }
  });

  if (!flagged) {
    console.log('  ✔ All records fall within the schema categories.');
  } else {
    console.log(
      `  ⚠ ${flagged}/${records.length} record(s) contain values outside the strict schema ` +
        'enum/type. They are inserted verbatim via the native driver to preserve the exact structure.'
    );
  }
}

async function run() {
  const mongoUri =
    process.env.connection_url ||
    process.env.DEMO_MONGO_URI ||
    process.env.MONGODB_URI;

  if (!mongoUri) {
    throw new Error(
      'Missing Mongo connection string. Set connection_url (preferred, matches the app) ' +
        'or DEMO_MONGO_URI / MONGODB_URI.'
    );
  }

  const dbName = process.env.ADP_DB_NAME || process.env.MONGO_DB_NAME;
  const collectionName = process.env.ADP_COLLECTION || COLLECTION_DEFAULT;
  const resetBeforeSeed = String(process.env.ADP_RESET || 'false').toLowerCase() === 'true';

  reportValidation(ADP_INTAKE_REQUESTS);

  const client = new MongoClient(mongoUri);

  try {
    await client.connect();
    const db = dbName ? client.db(dbName) : client.db();
    const collection = db.collection(collectionName);

    if (resetBeforeSeed) {
      const removed = await collection.deleteMany({ oppId: { $regex: '^OPP-20' } });
      console.log(`🧹 Reset: removed ${removed.deletedCount} existing OPP-20xx document(s).`);
    }

    const now = new Date();
    const ops = ADP_INTAKE_REQUESTS.map((doc) => ({
      updateOne: {
        filter: { oppId: doc.oppId },
        update: {
          $set: { ...doc, updatedAt: now },
          $setOnInsert: { createdAt: now },
        },
        upsert: true,
      },
    }));

    const result = await collection.bulkWrite(ops, { ordered: false });

    console.log('✅ ADP intake requests ingestion completed');
    console.log(`Database: ${db.databaseName}`);
    console.log(`Collection: ${collectionName}`);
    console.log(`Payload records: ${ADP_INTAKE_REQUESTS.length}`);
    console.log(`Matched: ${result.matchedCount}`);
    console.log(`Modified: ${result.modifiedCount}`);
    console.log(`Upserted: ${result.upsertedCount}`);
  } finally {
    await client.close();
  }
}

run().catch((error) => {
  console.error('❌ ADP intake requests ingestion failed:', error.message);
  process.exitCode = 1;
});
